const MAX_PROVIDER_RESPONSE_BYTES: usize = 1024 * 1024;
const PROVIDER_REQUEST_TIMEOUT: Duration = Duration::from_secs(10);

type DiscoveredClient = CoreClient<
    EndpointSet,
    EndpointNotSet,
    EndpointNotSet,
    EndpointNotSet,
    EndpointMaybeSet,
    EndpointMaybeSet,
>;

/// Server-only boundary between the browser flow and trusted OIDC provider.
/// State and nonce are generated by the adapter and retained server-side.
pub(crate) trait OidcProvider: Send + Sync {
    fn begin_login(&self) -> Result<OidcLogin, OidcError>;

    fn finish_login<'a>(
        &'a self,
        code: &'a str,
        verifier: &'a str,
        nonce: &'a str,
    ) -> impl Future<Output = Result<OidcIdentity, OidcError>> + Send + 'a;
}

/// One authorization request; secret fields must never be logged or serialized.
pub(crate) struct OidcLogin {
    pub(crate) authorization_url: String,
    pub(crate) state: String,
    pub(crate) pkce_verifier: String,
    pub(crate) nonce: String,
}

/// Validated subject and an upper bound on the `FleetIQ` session's lifetime.
pub(crate) struct OidcIdentity {
    pub(crate) identity: ExternalIdentity,
    pub(crate) expires_at: UnixTimeMillis,
}

/// Deliberately bounded diagnostics: upstream responses can contain credentials.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub(crate) enum OidcError {
    Operational,
    Rejected,
}

impl fmt::Display for OidcError {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter.write_str(match self {
            Self::Operational => "OIDC provider is unavailable or misconfigured",
            Self::Rejected => "OIDC authentication was rejected",
        })
    }
}

impl Error for OidcError {}

/// Maintained protocol library adapter; neither access nor refresh tokens escape.
pub(crate) struct OidcClient {
    configuration: BrowserIdentityConfig,
    client: DiscoveredClient,
    http: reqwest::Client,
}

impl OidcClient {
    pub(crate) async fn discover(configuration: BrowserIdentityConfig) -> Result<Self, OidcError> {
        let http = trust::http_client(&configuration)?;
        let client = discover_client(&configuration, &http).await?;
        Ok(Self {
            configuration,
            client,
            http,
        })
    }
}

impl OidcProvider for OidcClient {
    fn begin_login(&self) -> Result<OidcLogin, OidcError> {
        let (challenge, verifier) = PkceCodeChallenge::new_random_sha256();
        let (url, state, nonce) = self
            .client
            .authorize_url(
                AuthenticationFlow::<CoreResponseType>::AuthorizationCode,
                CsrfToken::new_random,
                Nonce::new_random,
            )
            .set_pkce_challenge(challenge)
            .url();
        Ok(OidcLogin {
            authorization_url: url.into(),
            state: state.secret().clone(),
            pkce_verifier: verifier.secret().clone(),
            nonce: nonce.secret().clone(),
        })
    }

    async fn finish_login(
        &self,
        code: &str,
        verifier: &str,
        nonce: &str,
    ) -> Result<OidcIdentity, OidcError> {
        // Refresh at each callback so key rotation does not force a restart. A
        // discovery outage fails closed; no unverified or stale-key fallback.
        let client = discover_client(&self.configuration, &self.http).await?;
        let http = BoundedHttpClient(self.http.clone());
        let tokens = client
            .exchange_code(AuthorizationCode::new(code.to_owned()))
            .map_err(|_| OidcError::Operational)?
            .set_pkce_verifier(PkceCodeVerifier::new(verifier.to_owned()))
            .request_async(&http)
            .await
            .map_err(|error| match error {
                RequestTokenError::ServerResponse(_) => OidcError::Rejected,
                _ => OidcError::Operational,
            })?;
        verify_identity(&self.configuration, &client, &tokens, nonce)
    }
}

async fn discover_client(
    configuration: &BrowserIdentityConfig,
    http: &reqwest::Client,
) -> Result<DiscoveredClient, OidcError> {
    let issuer =
        IssuerUrl::new(configuration.issuer().to_owned()).map_err(|_| OidcError::Operational)?;
    let bounded_http = BoundedHttpClient(http.clone());
    let metadata = CoreProviderMetadata::discover_async(issuer, &bounded_http)
        .await
        .map_err(|_| OidcError::Operational)?;
    client_from_metadata(configuration, metadata)
}

fn client_from_metadata(
    configuration: &BrowserIdentityConfig,
    metadata: CoreProviderMetadata,
) -> Result<DiscoveredClient, OidcError> {
    // The configured issuer is trusted, but discovered endpoints must retain
    // HTTPS and must not embed credentials or fragments. HTTP requests also
    // enforce this before contacting the discovery-selected JWKS endpoint.
    if metadata.issuer().as_str() != configuration.issuer()
        || !secure_endpoint(metadata.authorization_endpoint().as_str())
        || !secure_endpoint(metadata.jwks_uri().as_str())
        || !metadata
            .token_endpoint()
            .as_ref()
            .is_some_and(|url| secure_endpoint(url.as_str()))
    {
        return Err(OidcError::Operational);
    }
    // Discovery defaults to client_secret_basic when this field is omitted.
    // Some workforce providers advertise only client_secret_post. Both are
    // confidential-client methods over the already required HTTPS channel.
    let auth_type = match metadata.token_endpoint_auth_methods_supported() {
        None => AuthType::BasicAuth,
        Some(methods) if methods.contains(&CoreClientAuthMethod::ClientSecretBasic) => {
            AuthType::BasicAuth
        }
        Some(methods) if methods.contains(&CoreClientAuthMethod::ClientSecretPost) => {
            AuthType::RequestBody
        }
        Some(_) => return Err(OidcError::Operational),
    };
    let redirect =
        RedirectUrl::new(configuration.callback_url()).map_err(|_| OidcError::Operational)?;
    Ok(CoreClient::from_provider_metadata(
        metadata,
        ClientId::new(configuration.client_id().to_owned()),
        Some(ClientSecret::new(configuration.client_secret().to_owned())),
    )
    .set_auth_type(auth_type)
    .set_redirect_uri(redirect))
}

fn verify_identity(
    configuration: &BrowserIdentityConfig,
    client: &DiscoveredClient,
    tokens: &CoreTokenResponse,
    nonce: &str,
) -> Result<OidcIdentity, OidcError> {
    let id_token = tokens.id_token().ok_or(OidcError::Rejected)?;
    let verifier = client.id_token_verifier();
    let nonce = Nonce::new(nonce.to_owned());
    let claims = id_token
        .claims(&verifier, &nonce)
        .map_err(|_| OidcError::Rejected)?;
    // The library intentionally leaves azp policy to the consuming client.
    if claims
        .authorized_party()
        .as_ref()
        .is_some_and(|party| party.as_str() != configuration.client_id())
        || (claims.audiences().len() > 1 && claims.authorized_party().is_none())
    {
        return Err(OidcError::Rejected);
    }
    if let Some(expected_hash) = claims.access_token_hash() {
        let actual_hash = AccessTokenHash::from_token(
            tokens.access_token(),
            id_token.signing_alg().map_err(|_| OidcError::Rejected)?,
            id_token
                .signing_key(&verifier)
                .map_err(|_| OidcError::Rejected)?,
        )
        .map_err(|_| OidcError::Rejected)?;
        if &actual_hash != expected_hash {
            return Err(OidcError::Rejected);
        }
    }
    let subject =
        ExternalIdentitySubject::new(claims.subject().as_str()).map_err(|_| OidcError::Rejected)?;
    Ok(OidcIdentity {
        identity: ExternalIdentity::new(configuration.identity_authority().clone(), subject),
        expires_at: UnixTimeMillis::new(claims.expiration().timestamp_millis()),
    })
}

fn secure_endpoint(value: &str) -> bool {
    url::Url::parse(value).is_ok_and(|url| {
        url.scheme() == "https"
            && url.host_str().is_some()
            && url.username().is_empty()
            && url.password().is_none()
            && url.fragment().is_none()
    })
}

// A named future lifetime avoids the higher-ranked closure lifetime inference
// at the OIDC library's asynchronous HTTP boundary. Reqwest client clones share
// the connection pool; this does not start another networking runtime.
struct BoundedHttpClient(reqwest::Client);

impl<'a> AsyncHttpClient<'a> for BoundedHttpClient {
    type Error = OidcError;
    type Future = Pin<Box<dyn Future<Output = Result<HttpResponse, OidcError>> + Send + 'a>>;

    fn call(&'a self, request: HttpRequest) -> Self::Future {
        Box::pin(bounded_request(&self.0, request))
    }
}
async fn bounded_request(
    client: &reqwest::Client,
    request: HttpRequest,
) -> Result<HttpResponse, OidcError> {
    if !secure_endpoint(&request.uri().to_string()) {
        return Err(OidcError::Operational);
    }
    let (parts, body) = request.into_parts();
    let mut response = client
        .request(parts.method, parts.uri.to_string())
        .headers(parts.headers)
        .body(body)
        .send()
        .await
        .map_err(|_| OidcError::Operational)?;
    if response
        .content_length()
        .is_some_and(|length| length > MAX_PROVIDER_RESPONSE_BYTES as u64)
    {
        return Err(OidcError::Operational);
    }
    let mut result = HttpResponse::new(Vec::new());
    *result.status_mut() = response.status();
    *result.headers_mut() = response.headers().clone();
    while let Some(chunk) = response.chunk().await.map_err(|_| OidcError::Operational)? {
        if chunk.len() > MAX_PROVIDER_RESPONSE_BYTES.saturating_sub(result.body().len()) {
            return Err(OidcError::Operational);
        }
        result.body_mut().extend_from_slice(&chunk);
    }
    Ok(result)
}

